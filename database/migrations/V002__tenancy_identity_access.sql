-- =============================================================================
-- V002 - Tenancy, identity (ASP.NET Core Identity tables), tokens, RBAC
-- Global tables (no tenant_id): tenants, users, user_claims, user_logins,
--   user_tokens, permissions. Everything else carries tenant_id.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- tenants: one row per customer company (SaaS tenant)
-- -----------------------------------------------------------------------------
CREATE TABLE dx.tenants (
    id              uuid         NOT NULL DEFAULT uuidv7(),
    code            varchar(50)  NOT NULL,
    name            varchar(200) NOT NULL,
    default_locale  varchar(10)  NOT NULL DEFAULT 'vi',
    time_zone       varchar(64)  NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    is_active       boolean      NOT NULL DEFAULT true,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by      uuid,
    updated_at      timestamptz  NOT NULL DEFAULT now(),
    updated_by      uuid,
    CONSTRAINT pk_tenants PRIMARY KEY (id),
    CONSTRAINT uq_tenants_code UNIQUE (code),
    CONSTRAINT ck_tenants_code_format CHECK (code ~ '^[a-z0-9][a-z0-9-]{1,49}$')
);

-- -----------------------------------------------------------------------------
-- users: login accounts (ASP.NET Core Identity IdentityUser<Guid> + app columns).
-- Global so that one e-mail logs in once; tenant membership is in tenant_users.
-- -----------------------------------------------------------------------------
CREATE TABLE dx.users (
    id                      uuid          NOT NULL DEFAULT uuidv7(),
    user_name               varchar(256)  NOT NULL,
    normalized_user_name    varchar(256)  NOT NULL,
    email                   varchar(256)  NOT NULL,
    normalized_email        varchar(256)  NOT NULL,
    email_confirmed         boolean       NOT NULL DEFAULT false,
    password_hash           text,
    security_stamp          text,
    concurrency_stamp       text,
    phone_number            varchar(32),
    phone_number_confirmed  boolean       NOT NULL DEFAULT false,
    two_factor_enabled      boolean       NOT NULL DEFAULT false,
    lockout_end             timestamptz,
    lockout_enabled         boolean       NOT NULL DEFAULT true,
    access_failed_count     integer       NOT NULL DEFAULT 0,
    -- application columns
    full_name               varchar(200)  NOT NULL,
    preferred_locale        varchar(10),
    avatar_url              varchar(1000),
    must_change_password    boolean       NOT NULL DEFAULT false,
    last_login_at           timestamptz,
    is_active               boolean       NOT NULL DEFAULT true,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    created_by              uuid,
    updated_at              timestamptz   NOT NULL DEFAULT now(),
    updated_by              uuid,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_normalized_user_name UNIQUE (normalized_user_name),
    CONSTRAINT uq_users_normalized_email UNIQUE (normalized_email),
    CONSTRAINT ck_users_access_failed_count CHECK (access_failed_count >= 0)
);

CREATE TABLE dx.user_claims (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    user_id      uuid    NOT NULL,
    claim_type   text,
    claim_value  text,
    CONSTRAINT pk_user_claims PRIMARY KEY (id),
    CONSTRAINT fk_user_claims_user_id FOREIGN KEY (user_id) REFERENCES dx.users (id) ON DELETE CASCADE
);
CREATE INDEX ix_user_claims_user_id ON dx.user_claims (user_id);

-- External logins (Google / Microsoft later, D2)
CREATE TABLE dx.user_logins (
    login_provider         varchar(128) NOT NULL,
    provider_key           varchar(128) NOT NULL,
    provider_display_name  text,
    user_id                uuid         NOT NULL,
    CONSTRAINT pk_user_logins PRIMARY KEY (login_provider, provider_key),
    CONSTRAINT fk_user_logins_user_id FOREIGN KEY (user_id) REFERENCES dx.users (id) ON DELETE CASCADE
);
CREATE INDEX ix_user_logins_user_id ON dx.user_logins (user_id);

CREATE TABLE dx.user_tokens (
    user_id         uuid         NOT NULL,
    login_provider  varchar(128) NOT NULL,
    name            varchar(128) NOT NULL,
    value           text,
    CONSTRAINT pk_user_tokens PRIMARY KEY (user_id, login_provider, name),
    CONSTRAINT fk_user_tokens_user_id FOREIGN KEY (user_id) REFERENCES dx.users (id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- tenant_users: which tenants a user may sign in to
-- -----------------------------------------------------------------------------
CREATE TABLE dx.tenant_users (
    tenant_id   uuid        NOT NULL,
    user_id     uuid        NOT NULL,
    is_default  boolean     NOT NULL DEFAULT true,
    is_active   boolean     NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    created_by  uuid,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    updated_by  uuid,
    CONSTRAINT pk_tenant_users PRIMARY KEY (tenant_id, user_id),
    CONSTRAINT fk_tenant_users_tenant_id FOREIGN KEY (tenant_id) REFERENCES dx.tenants (id),
    CONSTRAINT fk_tenant_users_user_id FOREIGN KEY (user_id) REFERENCES dx.users (id) ON DELETE CASCADE
);
CREATE INDEX ix_tenant_users_user_id ON dx.tenant_users (user_id);
CREATE UNIQUE INDEX uq_tenant_users_user_id_default ON dx.tenant_users (user_id) WHERE is_default;

-- -----------------------------------------------------------------------------
-- refresh_tokens: rotating refresh tokens (cookie dx_rt). Only the SHA-256 hash
-- is stored. Reuse of a revoked token revokes the whole family_id.
-- -----------------------------------------------------------------------------
CREATE TABLE dx.refresh_tokens (
    id              uuid         NOT NULL DEFAULT uuidv7(),
    user_id         uuid         NOT NULL,
    tenant_id       uuid         NOT NULL,
    family_id       uuid         NOT NULL,
    token_hash      varchar(128) NOT NULL,
    expires_at      timestamptz  NOT NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    created_by_ip   varchar(64),
    user_agent      varchar(500),
    revoked_at      timestamptz,
    revoked_reason  varchar(50),
    replaced_by_id  uuid,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user_id FOREIGN KEY (user_id) REFERENCES dx.users (id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_tokens_tenant_id FOREIGN KEY (tenant_id) REFERENCES dx.tenants (id),
    CONSTRAINT fk_refresh_tokens_replaced_by_id FOREIGN KEY (replaced_by_id) REFERENCES dx.refresh_tokens (id)
);
CREATE INDEX ix_refresh_tokens_user_id ON dx.refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_family_id ON dx.refresh_tokens (family_id);
CREATE INDEX ix_refresh_tokens_expires_at ON dx.refresh_tokens (expires_at);

-- -----------------------------------------------------------------------------
-- account_tokens: one-time links sent by e-mail
--   purpose = invitation     -> employee record gets a new login account
--   purpose = password_reset -> forgot password
-- Expiry comes from tenant setting invitation_expiry_hours. Hash only.
-- employee_id FK is added in V004 (employees created there).
-- -----------------------------------------------------------------------------
CREATE TABLE dx.account_tokens (
    id           uuid         NOT NULL DEFAULT uuidv7(),
    tenant_id    uuid         NOT NULL,
    purpose      varchar(20)  NOT NULL,
    token_hash   varchar(128) NOT NULL,
    email        varchar(256) NOT NULL,
    user_id      uuid,
    employee_id  uuid,
    expires_at   timestamptz  NOT NULL,
    consumed_at  timestamptz,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    created_by   uuid,
    CONSTRAINT pk_account_tokens PRIMARY KEY (id),
    CONSTRAINT uq_account_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_account_tokens_purpose CHECK (purpose IN ('invitation', 'password_reset')),
    CONSTRAINT fk_account_tokens_tenant_id FOREIGN KEY (tenant_id) REFERENCES dx.tenants (id),
    CONSTRAINT fk_account_tokens_user_id FOREIGN KEY (user_id) REFERENCES dx.users (id) ON DELETE CASCADE
);
CREATE INDEX ix_account_tokens_tenant_id_email ON dx.account_tokens (tenant_id, email);

-- -----------------------------------------------------------------------------
-- RBAC: permissions are a global, code-defined catalog (seeded in V012);
-- roles are per tenant. No bypass by role name (D3).
-- -----------------------------------------------------------------------------
CREATE TABLE dx.permissions (
    id          uuid         NOT NULL DEFAULT uuidv7(),
    key         varchar(64)  NOT NULL,
    group_key   varchar(32)  NOT NULL,
    name        varchar(200) NOT NULL,
    name_en     varchar(200),
    sort_order  integer      NOT NULL DEFAULT 0,
    CONSTRAINT pk_permissions PRIMARY KEY (id),
    CONSTRAINT uq_permissions_key UNIQUE (key),
    CONSTRAINT ck_permissions_key_format CHECK (key ~ '^[a-z_]+(\.[a-z_]+)?$')
);

CREATE TABLE dx.roles (
    id           uuid          NOT NULL DEFAULT uuidv7(),
    tenant_id    uuid          NOT NULL,
    code         varchar(50)   NOT NULL,
    name         varchar(200)  NOT NULL,
    name_en      varchar(200),
    description  varchar(1000),
    is_system    boolean       NOT NULL DEFAULT false,
    created_at   timestamptz   NOT NULL DEFAULT now(),
    created_by   uuid,
    updated_at   timestamptz   NOT NULL DEFAULT now(),
    updated_by   uuid,
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uq_roles_tenant_id_code UNIQUE (tenant_id, code),
    CONSTRAINT fk_roles_tenant_id FOREIGN KEY (tenant_id) REFERENCES dx.tenants (id)
);

CREATE TABLE dx.role_permissions (
    tenant_id      uuid        NOT NULL,
    role_id        uuid        NOT NULL,
    permission_id  uuid        NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    created_by     uuid,
    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_tenant_id FOREIGN KEY (tenant_id) REFERENCES dx.tenants (id),
    CONSTRAINT fk_role_permissions_role_id FOREIGN KEY (role_id) REFERENCES dx.roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission_id FOREIGN KEY (permission_id) REFERENCES dx.permissions (id)
);
CREATE INDEX ix_role_permissions_tenant_id ON dx.role_permissions (tenant_id);
CREATE INDEX ix_role_permissions_permission_id ON dx.role_permissions (permission_id);

CREATE TABLE dx.user_roles (
    tenant_id   uuid        NOT NULL,
    user_id     uuid        NOT NULL,
    role_id     uuid        NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    created_by  uuid,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_tenant_id FOREIGN KEY (tenant_id) REFERENCES dx.tenants (id),
    CONSTRAINT fk_user_roles_user_id FOREIGN KEY (user_id) REFERENCES dx.users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role_id FOREIGN KEY (role_id) REFERENCES dx.roles (id) ON DELETE CASCADE
);
CREATE INDEX ix_user_roles_tenant_id_role_id ON dx.user_roles (tenant_id, role_id);
